    // Obtener color de card segun especialidad (10 especialidades)
    static Theme::CardGradient GradientForSpecialty(const std::string& sp) {
        if (sp == "Cardiology")             return Theme::CardGradient::Pink;
        if (sp == "Infectology")            return Theme::CardGradient::Orange;
        if (sp == "Neurology")              return Theme::CardGradient::Purple;
        if (sp == "Pneumology")             return Theme::CardGradient::Blue;
        if (sp == "Gastroenterology")       return Theme::CardGradient::Green;
        if (sp == "GynecologyObstetrics")   return Theme::CardGradient::Pink;
        if (sp == "PediatricSurgery")       return Theme::CardGradient::Green;
        if (sp == "EmergencyMedicine")      return Theme::CardGradient::Orange;
        if (sp == "PediatricEndocrinology") return Theme::CardGradient::Gold;
        if (sp == "Pediatrics")             return Theme::CardGradient::Blue;
        if (sp == "Nephrology")             return Theme::CardGradient::Purple;
        if (sp == "Endocrinology")          return Theme::CardGradient::Gold;
        if (sp == "InternalMedicine")       return Theme::CardGradient::Blue;
        return Theme::CardGradient::Gold;
    }

    static const char* IconForSpecialty(const std::string& sp) {
        if (sp == "Cardiology")             return "H";   // Heart
        if (sp == "Infectology")            return "V";   // Virus
        if (sp == "Neurology")              return "N";   // Nerve
        if (sp == "Pneumology")             return "P";   // Pulmonar
        if (sp == "Gastroenterology")       return "G";
        if (sp == "GynecologyObstetrics")   return "GO";  // Gineco-Obstetricia
        if (sp == "PediatricSurgery")       return "CP";  // Cirugia Pediatrica
        if (sp == "EmergencyMedicine")      return "UR";  // Urgencias
        if (sp == "PediatricEndocrinology") return "EP";  // Endocrino Pediatrica
        if (sp == "Pediatrics")             return "PD";  // Pediatria
        if (sp == "Nephrology")             return "NF";  // Nefrologia
        if (sp == "Endocrinology")          return "EN";  // Endocrinologia
        if (sp == "InternalMedicine")       return "MI";  // Medicina Interna
        return "M";  // Fallback: Medicina general
    }

    static const char* SpecialtyNameES(const std::string& sp) {
        if (sp == "Cardiology")             return "CARDIOLOGIA";
        if (sp == "Infectology")            return "INFECTOLOGIA";
        if (sp == "Neurology")              return "NEUROLOGIA";
        if (sp == "Pneumology")             return "NEUMOLOGIA";
        if (sp == "Gastroenterology")       return "GASTROENTEROLOGIA";
        if (sp == "GynecologyObstetrics")   return "GINECO-OBSTETRICIA";
        if (sp == "PediatricSurgery")       return "CIRUGIA PEDIATRICA";
        if (sp == "EmergencyMedicine")      return "URGENCIAS";
        if (sp == "PediatricEndocrinology") return "ENDOCRINOLOGIA PEDIATRICA";
        if (sp == "Pediatrics")             return "PEDIATRIA";
        if (sp == "Nephrology")             return "NEFROLOGIA";
        if (sp == "Endocrinology")          return "ENDOCRINOLOGIA";
        if (sp == "InternalMedicine")       return "MEDICINA INTERNA";
        return "MEDICINA INTERNA";
    }

    static const char* DifficultyBadge(const std::string& d) {
        if (d == "basic")        return "BASICO";
        if (d == "intermediate") return "INTERMEDIO";
        if (d == "advanced")     return "AVANZADO";
        if (d == "expert")       return "EXPERTO";
        return "-";
    }

    void CasesListView::Render(AppContext& ctx,
                                ImFont* fontHuge, ImFont* fontLarge,
                                ImFont* fontMedium, ImFont* fontRegular,
                                ImFont* fontSmall) {
        using namespace Theme::Colors;

        // Titulo
        if (fontLarge) ImGui::PushFont(fontLarge);
        ImGui::PushStyleColor(ImGuiCol_Text, TextTitle);
        ImGui::Text("Casos Clinicos");
        ImGui::PopStyleColor();
        if (fontLarge) ImGui::PopFont();

        if (fontRegular) ImGui::PushFont(fontRegular);
        ImGui::PushStyleColor(ImGuiCol_Text, TextSecondary);
        ImGui::Text("Selecciona un caso para iniciar la sesion clinica interactiva  |  %zu disponibles",
                    ctx.casesList.size());
        ImGui::PopStyleColor();
        if (fontRegular) ImGui::PopFont();

        ImGui::Dummy(ImVec2(0, 20));

        // Cards de casos - 1 por fila para verse grande
        for (size_t i = 0; i < ctx.casesList.size(); ++i) {
            const auto& c = ctx.casesList[i];

            ImDrawList* dl = ImGui::GetWindowDrawList();
            ImVec2 pos = ImGui::GetCursorScreenPos();
            float avail = ImGui::GetContentRegionAvail().x;
            float cardH = 140.0f;
            ImVec2 cardMax(pos.x + avail, pos.y + cardH);

            // Sombra
            Theme::DrawShadowedRect(dl, pos, cardMax, 16.0f,
                ImGui::ColorConvertFloat4ToU32(ShadowStrong));

            // Fondo blanco
            dl->AddRectFilled(pos, cardMax, IM_COL32(255, 255, 255, 255), 16.0f);

            // Banda lateral de color (izquierda) segun especialidad
            Theme::CardGradient g = GradientForSpecialty(c.specialty);
            ImVec4 topG, botG;
            Theme::GetGradientColors(g, topG, botG);
            ImU32 topU = ImGui::ColorConvertFloat4ToU32(topG);
            ImU32 botU = ImGui::ColorConvertFloat4ToU32(botG);

            ImVec2 bandMin = pos;
            ImVec2 bandMax(pos.x + 8, cardMax.y);
            dl->AddRectFilledMultiColor(bandMin, bandMax, topU, topU, botU, botU);

            // Icono cuadro grande a la izquierda
            ImVec2 iconMin(pos.x + 30, pos.y + 30);
            ImVec2 iconMax(iconMin.x + 80, iconMin.y + 80);
            dl->AddRectFilledMultiColor(iconMin, iconMax, topU, topU, botU, botU);
            // Bordes redondeados del icono
            dl->AddRect(iconMin, iconMax, 0, 12.0f);

            if (fontHuge) ImGui::PushFont(fontHuge);
            const char* iconTxt = IconForSpecialty(c.specialty);
            ImVec2 iconTxtSize = ImGui::CalcTextSize(iconTxt);
            ImVec2 iconTxtPos(iconMin.x + (80 - iconTxtSize.x) * 0.5f,
                              iconMin.y + (80 - iconTxtSize.y) * 0.5f);
            dl->AddText(iconTxtPos, IM_COL32(255, 255, 255, 255), iconTxt);
            if (fontHuge) ImGui::PopFont();

            // Info del caso a la derecha del icono
            float textX = pos.x + 130;

            // Badge especialidad arriba
            if (fontSmall) ImGui::PushFont(fontSmall);
            const char* spName = SpecialtyNameES(c.specialty);
            dl->AddText(ImVec2(textX, pos.y + 22),
                        ImGui::ColorConvertFloat4ToU32(topG), spName);
            if (fontSmall) ImGui::PopFont();

            // Titulo
            if (fontMedium) ImGui::PushFont(fontMedium);
            std::string titulo = c.title;
            if (titulo.length() > 80) titulo = titulo.substr(0, 77) + "...";
            dl->AddText(ImVec2(textX, pos.y + 42),
                        ImGui::ColorConvertFloat4ToU32(TextTitle), titulo.c_str());
            if (fontMedium) ImGui::PopFont();

            // Info del paciente
            if (fontRegular) ImGui::PushFont(fontRegular);
            std::string patientInfo = "Paciente: ";
            if (c.patient.contains("full_name")) {
                patientInfo += c.patient["full_name"].get<std::string>();
            }
            if (c.patient.contains("age")) {
                patientInfo += " (" + std::to_string(c.patient["age"].get<int>()) + " anos)";
            }
            patientInfo += "  |  Setting: " + c.setting;

            dl->AddText(ImVec2(textX, pos.y + 78),
                        ImGui::ColorConvertFloat4ToU32(TextSecondary), patientInfo.c_str());

            // Chief complaint (segunda linea)
            std::string cc = c.chiefComplaint;
            if (cc.length() > 90) cc = cc.substr(0, 87) + "...";
            dl->AddText(ImVec2(textX, pos.y + 102),
                        ImGui::ColorConvertFloat4ToU32(TextDim), cc.c_str());
            if (fontRegular) ImGui::PopFont();

            // Badge de dificultad (esquina superior derecha)
            if (fontSmall) ImGui::PushFont(fontSmall);
            const char* difTxt = DifficultyBadge(c.difficulty);
            ImVec2 difSize = ImGui::CalcTextSize(difTxt);
            ImVec2 difBoxMin(cardMax.x - difSize.x - 40, pos.y + 20);
            ImVec2 difBoxMax(cardMax.x - 20, pos.y + 44);
            dl->AddRectFilled(difBoxMin, difBoxMax,
                              ImGui::ColorConvertFloat4ToU32(BgSubtle), 6.0f);
            dl->AddText(ImVec2(difBoxMin.x + 10, difBoxMin.y + 5),
                        ImGui::ColorConvertFloat4ToU32(TextSecondary), difTxt);
            if (fontSmall) ImGui::PopFont();

            // Boton INICIAR a la derecha
            ImVec2 btnPos(cardMax.x - 200, cardMax.y - 50);
            ImVec2 btnMax(cardMax.x - 24, cardMax.y - 20);
            dl->AddRectFilledMultiColor(btnPos, btnMax, topU, topU, botU, botU);

            if (fontRegular) ImGui::PushFont(fontRegular);
            const char* btnTxt = "INICIAR SESION  >";
            ImVec2 btnTxtSize = ImGui::CalcTextSize(btnTxt);
            ImVec2 btnTxtPos(btnPos.x + ((btnMax.x - btnPos.x) - btnTxtSize.x) * 0.5f,
                             btnPos.y + ((btnMax.y - btnPos.y) - btnTxtSize.y) * 0.5f);
            dl->AddText(btnTxtPos, IM_COL32(255, 255, 255, 255), btnTxt);
            if (fontRegular) ImGui::PopFont();

            // Deteccion click por rectangulo
            bool hovered = ImGui::IsMouseHoveringRect(pos, cardMax);
            bool clicked = hovered && ImGui::IsMouseClicked(ImGuiMouseButton_Left);

            if (hovered) {
                dl->AddRect(pos, cardMax,
                            ImGui::ColorConvertFloat4ToU32(topG), 16.0f, 0, 2.5f);
                ImGui::SetMouseCursor(ImGuiMouseCursor_Hand);
            }

            if (clicked) {
                ctx.StartSession(c);
                ctx.NavigateTo(AppView::PatientSession);
            }

            ImGui::SetCursorScreenPos(ImVec2(pos.x, cardMax.y));

            ImGui::Dummy(ImVec2(0, 16));
        }
    }

